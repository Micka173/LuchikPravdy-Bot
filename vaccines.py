def get_vaccines_by_age(age_months):
    done, soon, future = [], [], []
    for months, name in VACCINES:
        if age_months >= months:
            done.append((months, name))
        elif age_months + 2 >= months:
            soon.append((months, name))
        else:
            future.append((months, name))
    return done, soon, future